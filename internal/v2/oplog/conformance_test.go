// incompressibleBytes returns n bytes gzip cannot shrink, derived from a hash
// chain so the value is identical on every machine and every Go release. A
// math/rand stream is not: its algorithm is a documented implementation detail
// and the global source is randomly seeded since Go 1.20.
func incompressibleBytes(n int) []byte {
	out := make([]byte, 0, n+sha256.Size)
	var ctr [8]byte
	for i := uint64(0); len(out) < n; i++ {
		binary.BigEndian.PutUint64(ctr[:], i)
		sum := sha256.Sum256(ctr[:])
		out = append(out, sum[:]...)
	}
	return out[:n]
}

// prePadLength reports the framed length before bucket padding, derived from
// the frozen layout via the package's own SealedRegion so the test does not
// restate offsets.
func prePadLength(t *testing.T, b []byte) int {
	t.Helper()
	start, end, err := blob.SealedRegion(b)
	if err != nil {
		t.Fatalf("sealed region: %v", err)
	}
	payloadLen := int(binary.BigEndian.Uint32(b[start : start+4]))
	if start+4+payloadLen > end {
		t.Fatalf("payload length %d runs past the sealed region", payloadLen)
	}
	return start + 4 + payloadLen + blob.TagSize
}

// bucketEdgePlaintext finds a plaintext whose framed length lands exactly one
// byte under bucket bucketIdx, i.e. a blob with exactly one padding byte.
//
// It is the fixture that catches an off-by-one anywhere in the offset math:
// an ordinary fixture has hundreds of bytes of slack, so a reader that
// miscounted the header by one would still find the payload.
//
// gzip of incompressible input runs about len+18, and the framing overhead is
// ~83, so the answer is near bucket-101; the window is wide enough to absorb
// deflate's block accounting without scanning the whole bucket.
func bucketEdgePlaintext(t *testing.T, e blob.Envelope, bucketIdx int) []byte {
	t.Helper()
	bucket := blob.Buckets[bucketIdx]
	target := bucket - 1
	var sealer blob.PlaintextSealer
	for n := bucket - 200; n < bucket; n++ {
		if n < 1 {
			continue
		}
		pt := incompressibleBytes(n)
		s, err := sealer.Seal(e, pt)
		if err != nil {
			continue
		}
		if s.SizeBucket < bucket {
			continue // still fits a smaller rung
		}
		if s.SizeBucket > bucket {
			break // overshot this rung entirely
		}
		if prePadLength(t, s.Bytes) == target {
			return pt
		}
	}
	t.Fatalf("no plaintext frames to exactly %d bytes (bucket %d)", target, bucket)
	return nil
}

// escapeTrapOps is an op whose payload holds every character the two encoders
// treat differently, in the Go->TypeScript direction. Go's encoding/json escapes
// <, >, & and U+2028/U+2029 as \uXXXX; JSON.stringify emits them literally. The
// TypeScript side has a mirror fixture; without this one the asymmetry was only
// ever exercised in the direction where Go is the READER.
func escapeTrapOps() []Op {
	parent := int64(1)
	return []Op{{
		V:             SchemaVersion,
		Type:          OpTxnEdited,
		OpID:          "01J000000000000000000000G1",
		AuthoredAt:    time.Date(2026, 6, 5, 10, 0, 0, 0, time.UTC),
		Entity:        &EntityRef{Kind: "txn", ID: "T1"},
		ParentVersion: &parent,
		Payload: json.RawMessage(`{"merchant_raw":"كارفور",` +
			`"note":"Smith & Sons <flagged> \u2028 second line \u2029 end",` +
			`"amount_minor":"25000"}`),
	}}
}

// TestWriteConformanceFixtures regenerates the committed fixtures. It is opt-in
// (see writeFixturesEnv) because a golden file the test suite rewrites on every
// run is not a golden file.
//
//	LEDGER_WRITE_CONFORMANCE=1 go test ./internal/v2/oplog/ -run TestWriteConformanceFixtures -v
func TestWriteConformanceFixtures(t *testing.T) {
	if os.Getenv(writeFixturesEnv) != "1" {
		t.Skipf("set %s=1 to regenerate conformance/blob and conformance/op", writeFixturesEnv)
	}

	blobDir := filepath.Join(conformanceDir(), "blob")
	opDir := filepath.Join(conformanceDir(), "op")
	for _, d := range []string{blobDir, opDir} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
	}

	ops, err := EncodeBlob(goldenOps())
	if err != nil {
		t.Fatal(err)
	}
	raw, err := EncodeRawBody(goldenRawBody())
	if err != nil {
		t.Fatal(err)
	}
	checkpoint, err := EncodeCheckpointPayload(goldenCheckpointHeads())
	if err != nil {
		t.Fatal(err)
	}

	edgeEnv := blob.Envelope{UserID: conformanceUser, Stream: blob.StreamHot, WriterID: "dev-a", WriterCounter: 8}
	bigEdgeEnv := blob.Envelope{UserID: conformanceUser, Stream: blob.StreamHot, WriterID: "dev-a", WriterCounter: 12}
	type spec struct {
		file      string
		note      string
		kind      string
		env       blob.Envelope
		plaintext []byte
	}
	specs := []spec{
		{
			file:      "hot-dev-a-7.bin",
			note:      "a hot op blob: the golden op JSON of TestGoldenOpBytes, sealed at (dev-a, hot, 7)",
			kind:      KindOps,
			env:       blob.Envelope{UserID: conformanceUser, Stream: blob.StreamHot, WriterID: "dev-a", WriterCounter: 7},
			plaintext: ops,
		},
		{
			file:      "cold-ingest-3.bin",
			note:      "a cold raw-body blob: invariant I16 says this stream never carries ops",
			kind:      KindRawBody,
			env:       blob.Envelope{UserID: conformanceUser, Stream: blob.StreamCold, WriterID: IngestWriterID, WriterCounter: 3},
			plaintext: raw,
		},
		{
			file:      "hot-dev-a-8-bucket-edge.bin",
			note:      "a blob framed to exactly one byte under the 1 KiB bucket: one padding byte, so an off-by-one in any offset is fatal",
			kind:      KindRawBody,
			env:       edgeEnv,
			plaintext: nil, // filled in below; it depends on the envelope's AAD length
		},
		{
			file:      "hot-dev-a-11-escapes.bin",
			note:      "an op payload holding every character Go escapes and JSON.stringify does not, plus non-ASCII: the Go->TypeScript direction of that asymmetry",
			kind:      KindOps,
			env:       blob.Envelope{UserID: conformanceUser, Stream: blob.StreamHot, WriterID: "dev-a", WriterCounter: 11},
			plaintext: mustEncodeBlob(t, escapeTrapOps()),
		},
		{
			file:      "hot-dev-a-12-bucket-edge-4k.bin",
			note:      "one byte under rung 1 of the ladder: without it every fixture sits in bucket 0 and no blob crosses the executor boundary on a higher rung",
			kind:      "",
			env:       bigEdgeEnv,
			plaintext: nil, // filled in below
		},
	}
	// Both edge fixtures are raw bytes rather than records, so they carry no
	// kind, and their plaintexts depend on their envelope's AAD length.
	specs[2].plaintext = bucketEdgePlaintext(t, edgeEnv, 0)
	specs[2].kind = ""
	specs[4].plaintext = bucketEdgePlaintext(t, bigEdgeEnv, 1)

	var sealer blob.PlaintextSealer
	man := blobManifest{
		Note: "Sealed by internal/v2/oplog TestWriteConformanceFixtures. " +
			"Regenerate with LEDGER_WRITE_CONFORMANCE=1; do not hand-edit. " +
			"Both executors open these bytes; the framing is frozen (see internal/v2/blob).",
		Buckets:     blob.Buckets,
		NonceSize:   blob.NonceSize,
		TagSize:     blob.TagSize,
		ZeroHashHex: hex.EncodeToString(blob.ZeroHash[:]),
	}
	for _, s := range specs {
		sealed, err := sealer.Seal(s.env, s.plaintext)
		if err != nil {
			t.Fatalf("%s: %v", s.file, err)
		}
		if err := os.WriteFile(filepath.Join(blobDir, s.file), sealed.Bytes, 0o644); err != nil {
			t.Fatal(err)
		}
		man.Fixtures = append(man.Fixtures, blobFixture{
			File: s.file,
			Note: s.note,
			Kind: s.kind,
			Envelope: fixtureEnvelope{
				UserID:        s.env.UserID.String(),
				Stream:        s.env.Stream,
				WriterID:      s.env.WriterID,
				WriterCounter: strconv.FormatInt(s.env.WriterCounter, 10),
			},
			ExpectAAD:             string(s.env.AAD()),
			ExpectBucket:          sealed.SizeBucket,
			ExpectPlaintextBase64: base64.StdEncoding.EncodeToString(s.plaintext),
			ExpectPrePadLength:    prePadLength(t, sealed.Bytes),
		})
	}

	// The chain vector, generated rather than transcribed. chain_test.go pins
	// the same two hashes against literals, so the two must agree here.
	prev := blob.ZeroHash
	for _, step := range []struct {
		fill byte
		n    int
	}{{0xab, 1024}, {0xcd, 1024}} {
		body := bytes.Repeat([]byte{step.fill}, step.n)
		h := blob.Hash(prev, blob.Sealed{Bytes: body, SizeBucket: step.n})
		man.ChainSteps = append(man.ChainSteps, chainStep{
			FillByte:   hex.EncodeToString([]byte{step.fill}),
			Length:     step.n,
			ExpectHash: hex.EncodeToString(h[:]),
		})
		prev = h
	}
	writeJSONFixture(t, filepath.Join(blobDir, "manifest.json"), man)

	opMan := opManifest{
		Note: "Encoded by internal/v2/oplog TestWriteConformanceFixtures. " +
			"parent_version is a raw JSON NUMBER on the wire and a decimal string in this manifest; " +
			"money and counters are decimal strings on the wire. " +
			"authored_at_cases pin PARSED INSTANTS, never strings: Go's RFC3339Nano trims trailing " +
			"zeros where JavaScript's toISOString pads to three digits.",
		SchemaVersion:          SchemaVersion,
		GoldenOpsBase64:        base64.StdEncoding.EncodeToString(ops),
		GoldenRawBodyBase64:    base64.StdEncoding.EncodeToString(raw),
		GoldenCheckpointBase64: base64.StdEncoding.EncodeToString(checkpoint),
	}
	for _, ty := range Types {
		opMan.Types = append(opMan.Types, string(ty))
		if ty.ParentFree() {
			opMan.ParentFree = append(opMan.ParentFree, string(ty))
		}
	}
	decoded, err := DecodeBlob(ops)
	if err != nil {
		t.Fatal(err)
	}
	for _, o := range decoded {
		e := opExpect{
			Type:             string(o.Type),
			OpID:             o.OpID,
			AuthoredAtUnixMs: strconv.FormatInt(o.AuthoredAt.UnixMilli(), 10),
			HasEntity:        o.Entity != nil,
			IngestID:         o.IngestID,
		}
		if o.ParentVersion != nil {
			s := strconv.FormatInt(*o.ParentVersion, 10)
			e.ParentVersion = &s
		}
		opMan.ExpectOps = append(opMan.ExpectOps, e)
	}
	// The sub-millisecond, offset and leap-year cases, decoded by this build.
	// TestDecodeTruncatesAuthoredAtToMilliseconds asserts the same rule against
	// Go literals; here the answers are handed to the other executor.
	for _, wire := range timeAcceptCases {
		got, err := DecodeBlob(timeProbeBlob(wire))
		if err != nil {
			t.Fatalf("%s: %v", wire, err)
		}
		opMan.AuthoredAtCases = append(opMan.AuthoredAtCases, timeCase{
			Wire:         wire,
			ExpectUnixMs: strconv.FormatInt(got[0].AuthoredAt.UnixMilli(), 10),
		})
	}
	// The parent_version asymmetry, encoded by this executor so the other can
	// check it refuses exactly these bytes.
	overflow := int64(1)<<53 + 1
	overflowBlob, err := EncodeBlob([]Op{{
		V:             SchemaVersion,
		Type:          OpTxnCategorized,
		OpID:          "01J000000000000000000000P1",
		AuthoredAt:    time.Date(2026, 6, 5, 10, 0, 0, 0, time.UTC),
		Entity:        &EntityRef{Kind: "txn", ID: "T1"},
		ParentVersion: &overflow,
		Payload:       json.RawMessage(`{"category":"groceries"}`),
	}})
	if err != nil {
		t.Fatal(err)
	}
	opMan.ParentVersionOverflowBase64 = base64.StdEncoding.EncodeToString(overflowBlob)
	opMan.ParentVersionOverflow = strconv.FormatInt(overflow, 10)

	for _, wire := range timeRejectCases {
		if _, err := DecodeBlob(timeProbeBlob(wire)); err == nil {
			t.Fatalf("authored_at %q must be refused before it can be written as a reject case", wire)
		}
		opMan.AuthoredAtRejects = append(opMan.AuthoredAtRejects, wire)
	}
	writeJSONFixture(t, filepath.Join(opDir, "manifest.json"), opMan)
}

// timeProbeBlob is a minimal one-op blob carrying an arbitrary authored_at
// string, used to ask each executor what instant it reads out of it.
func timeProbeBlob(wire string) []byte {
	return []byte(`{"v":1,"kind":"ops","ops":[{"v":1,"type":"rate_set",` +
		`"op_id":"01J000000000000000000000R1","authored_at":"` + wire + `",` +
		`"parent_version":null,"payload":{}}]}`)
}

func writeJSONFixture(t *testing.T, path string, v any) {
	t.Helper()
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, append(b, '\n'), 0o644); err != nil {
		t.Fatal(err)
	}
}

// ---------------------------------------------------------------------------
// The always-on halves: this build must still agree with what it wrote, and
// with what the other executor writes.
// ---------------------------------------------------------------------------

func readBlobManifest(t *testing.T, dir string) blobManifest {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(dir, "manifest.json"))
	if err != nil {
		// Not a skip. A missing fixture set means the cross-executor gate is not
		// running, and a gate that silently disables itself is worse than no gate.
		t.Fatalf("conformance manifest is missing (%v); regenerate with %s=1", err, writeFixturesEnv)
	}
	var man blobManifest
	if err := json.Unmarshal(b, &man); err != nil {
		t.Fatal(err)
	}
	if len(man.Fixtures) == 0 {
		t.Fatal("conformance manifest lists no fixtures")
	}
	return man
}

// checkFixtures opens every fixture in dir and asserts it still yields the
// pinned plaintext at the pinned position. It is shared by the Go-authored and
// the TypeScript-authored sets: the assertion is the same in both directions,
// which is the point of a frozen format.
func checkFixtures(t *testing.T, dir string) {
	t.Helper()
	man := readBlobManifest(t, dir)
	var sealer blob.PlaintextSealer
	for _, f := range man.Fixtures {
		t.Run(f.File, func(t *testing.T) {
			raw, err := os.ReadFile(filepath.Join(dir, f.File))
			if err != nil {
				t.Fatal(err)
			}
			if len(raw) != f.ExpectBucket {
				t.Fatalf("blob is %d bytes, manifest says bucket %d", len(raw), f.ExpectBucket)
			}
			env := f.Envelope.blobEnvelope(t)
			if got := string(env.AAD()); got != f.ExpectAAD {
				t.Fatalf("AAD is %q, manifest says %q", got, f.ExpectAAD)
			}
			if embedded, err := blob.EmbeddedAAD(raw); err != nil {
				t.Fatalf("embedded AAD: %v", err)
			} else if string(embedded) != f.ExpectAAD {
				t.Fatalf("embedded AAD is %q, manifest says %q", embedded, f.ExpectAAD)
			}
			if got := prePadLength(t, raw); got != f.ExpectPrePadLength {
				t.Fatalf("framed length before padding is %d, manifest says %d", got, f.ExpectPrePadLength)
			}

			plaintext, err := sealer.Open(env, blob.Sealed{Bytes: raw, SizeBucket: len(raw)})
			if err != nil {
				t.Fatalf("open: %v", err)
			}
			want, err := base64.StdEncoding.DecodeString(f.ExpectPlaintextBase64)
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(plaintext, want) {
				t.Fatalf("plaintext differs from the manifest:\n got %q\nwant %q", plaintext, want)
			}

			// Moving the blob one position along must be refused. Without this
			// the whole fixture set would pass against an Open that ignored the
			// AAD entirely.
			moved := env
			moved.WriterCounter++
			if _, err := sealer.Open(moved, blob.Sealed{Bytes: raw, SizeBucket: len(raw)}); err == nil {
				t.Fatal("opening the fixture at the next counter must fail")
			}

			switch f.Kind {
			case KindOps:
				if _, err := DecodeBlob(plaintext); err != nil {
					t.Fatalf("decode ops: %v", err)
				}
				if _, err := DecodeRawBody(plaintext); err == nil {
					t.Fatal("an op blob must not decode as a raw body (invariant I16)")
				}
			case KindRawBody:
				rb, err := DecodeRawBody(plaintext)
				if err != nil {
					t.Fatalf("decode raw body: %v", err)
				}
				// The PAYLOAD is decoded, not just the record around it.
				// DecodeRawBody used to hand back RawBase64 as an unexamined
				// string, and this check only called DecodeRawBody — so the cold
				// record's actual content never crossed the executor boundary at
				// all, and a TypeScript encoder emitting unpadded base64url
				// passed this gate green.
				raw, err := base64.StdEncoding.DecodeString(rb.RawBase64)
				if err != nil {
					t.Fatalf("raw_base64 does not decode: %v", err)
				}
				if len(raw) == 0 {
					t.Fatal("cold fixtures must carry a non-empty body, or this check proves nothing")
				}
				if got := base64.StdEncoding.EncodeToString(raw); got != rb.RawBase64 {
					t.Fatalf("raw_base64 is not canonical standard base64:\n got %s\nwant %s", rb.RawBase64, got)
				}
				if _, err := DecodeBlob(plaintext); err == nil {
					t.Fatal("a raw-body blob must not decode as ops (invariant I16)")
				}
			}
		})
	}
}

// TestConformanceFixturesAreWhatThisBuildProduces is the Go half of the
// dual-executor gate: the committed bytes must still open, at the same
// positions, to the same plaintexts, under this build.
func TestConformanceFixturesAreWhatThisBuildProduces(t *testing.T) {
	dir := filepath.Join(conformanceDir(), "blob")
	checkFixtures(t, dir)

	man := readBlobManifest(t, dir)
	// The layout constants travel in the manifest so the TypeScript port has one
	// source for them rather than a hand-copied ladder.
	if len(man.Buckets) != len(blob.Buckets) {
		t.Fatalf("manifest lists %d buckets, this build has %d", len(man.Buckets), len(blob.Buckets))
	}
	for i, b := range blob.Buckets {
		if man.Buckets[i] != b {
			t.Fatalf("bucket %d is %d, manifest says %d", i, b, man.Buckets[i])
		}
	}
	if man.NonceSize != blob.NonceSize || man.TagSize != blob.TagSize {
		t.Fatalf("reserved slot sizes moved: manifest has nonce %d tag %d, build has %d/%d",
			man.NonceSize, man.TagSize, blob.NonceSize, blob.TagSize)
	}
	if man.ZeroHashHex != hex.EncodeToString(blob.ZeroHash[:]) {
		t.Fatalf("chain genesis moved: manifest %s", man.ZeroHashHex)
	}

	prev := blob.ZeroHash
	for i, step := range man.ChainSteps {
		fill, err := hex.DecodeString(step.FillByte)
		if err != nil || len(fill) != 1 {
			t.Fatalf("chain step %d has fill byte %q", i, step.FillByte)
		}
		body := bytes.Repeat(fill, step.Length)
		h := blob.Hash(prev, blob.Sealed{Bytes: body, SizeBucket: step.Length})
		if got := hex.EncodeToString(h[:]); got != step.ExpectHash {
			t.Fatalf("chain step %d hashes to %s, manifest says %s", i, got, step.ExpectHash)
		}
		prev = h
	}
	if len(man.ChainSteps) == 0 {
		t.Fatal("the manifest carries no chain vector")
	}
}

// TestOpConformanceManifestMatchesThisBuild does the same for the op wire
// model: the golden bytes must still encode and decode identically here.
func TestOpConformanceManifestMatchesThisBuild(t *testing.T) {
	b, err := os.ReadFile(filepath.Join(conformanceDir(), "op", "manifest.json"))
	if err != nil {
		t.Fatalf("op manifest is missing (%v); regenerate with %s=1", err, writeFixturesEnv)
	}
	var man opManifest
	if err := json.Unmarshal(b, &man); err != nil {
		t.Fatal(err)
	}
	if man.SchemaVersion != SchemaVersion {
		t.Fatalf("manifest is for schema v%d, this build is v%d", man.SchemaVersion, SchemaVersion)
	}
	if len(man.Types) != len(Types) {
		t.Fatalf("manifest lists %d op types, this build has %d", len(man.Types), len(Types))
	}
	for i, ty := range Types {
		if man.Types[i] != string(ty) {
			t.Fatalf("op type %d is %q, manifest says %q", i, ty, man.Types[i])
		}
	}
	for _, ty := range man.ParentFree {
		if !OpType(ty).ParentFree() {
			t.Fatalf("manifest calls %q parent-free and this build does not", ty)
		}
	}

	ops, err := EncodeBlob(goldenOps())
	if err != nil {
		t.Fatal(err)
	}
	if got := base64.StdEncoding.EncodeToString(ops); got != man.GoldenOpsBase64 {
		want, _ := base64.StdEncoding.DecodeString(man.GoldenOpsBase64)
		t.Fatalf("op blob encoding changed:\n got %s\nwant %s", ops, want)
	}
	raw, err := EncodeRawBody(goldenRawBody())
	if err != nil {
		t.Fatal(err)
	}
	if got := base64.StdEncoding.EncodeToString(raw); got != man.GoldenRawBodyBase64 {
		t.Fatalf("raw body encoding changed: %s", raw)
	}
	cp, err := EncodeCheckpointPayload(goldenCheckpointHeads())
	if err != nil {
		t.Fatal(err)
	}
	if got := base64.StdEncoding.EncodeToString(cp); got != man.GoldenCheckpointBase64 {
		t.Fatalf("checkpoint payload encoding changed: %s", cp)
	}

	decoded, err := DecodeBlob(ops)
	if err != nil {
		t.Fatal(err)
	}
	if len(decoded) != len(man.ExpectOps) {
		t.Fatalf("golden blob has %d ops, manifest expects %d", len(decoded), len(man.ExpectOps))
	}
	for i, want := range man.ExpectOps {
		got := decoded[i]
		if string(got.Type) != want.Type || got.OpID != want.OpID {
			t.Fatalf("op %d is %s/%s, manifest says %s/%s", i, got.Type, got.OpID, want.Type, want.OpID)
		}
		if ms := strconv.FormatInt(got.AuthoredAt.UnixMilli(), 10); ms != want.AuthoredAtUnixMs {
			t.Fatalf("op %d authored at %s ms, manifest says %s", i, ms, want.AuthoredAtUnixMs)
		}
		if (got.Entity != nil) != want.HasEntity {
			t.Fatalf("op %d entity presence disagrees with the manifest", i)
		}
		if got.IngestID != want.IngestID {
			t.Fatalf("op %d ingest_id is %q, manifest says %q", i, got.IngestID, want.IngestID)
		}
		switch {
		case got.ParentVersion == nil && want.ParentVersion != nil:
			t.Fatalf("op %d has no parent_version, manifest says %s", i, *want.ParentVersion)
		case got.ParentVersion != nil && want.ParentVersion == nil:
			t.Fatalf("op %d has parent_version %d, manifest says null", i, *got.ParentVersion)
		case got.ParentVersion != nil && strconv.FormatInt(*got.ParentVersion, 10) != *want.ParentVersion:
			t.Fatalf("op %d parent_version is %d, manifest says %s", i, *got.ParentVersion, *want.ParentVersion)
		}
	}

	if len(man.AuthoredAtCases) == 0 {
		t.Fatal("the manifest carries no authored_at cases")
	}
	for _, c := range man.AuthoredAtCases {
		got, err := DecodeBlob(timeProbeBlob(c.Wire))
		if err != nil {
			t.Fatalf("%s: %v", c.Wire, err)
		}
		if ms := strconv.FormatInt(got[0].AuthoredAt.UnixMilli(), 10); ms != c.ExpectUnixMs {
			t.Fatalf("%s decodes to %s ms, manifest says %s", c.Wire, ms, c.ExpectUnixMs)
		}
	}
	// Go reads the overflow blob exactly; TypeScript must refuse it. Asserting
	// the Go half here is what makes the TypeScript refusal meaningful rather
	// than a test of a string nobody produces.
	overflowBlob, err := base64.StdEncoding.DecodeString(man.ParentVersionOverflowBase64)
	if err != nil {
		t.Fatal(err)
	}
	overflowOps, err := DecodeBlob(overflowBlob)
	if err != nil {
		t.Fatalf("the parent_version overflow blob must decode HERE: %v", err)
	}
	if len(overflowOps) != 1 || overflowOps[0].ParentVersion == nil {
		t.Fatal("the parent_version overflow blob lost its parent_version")
	}
	if got := strconv.FormatInt(*overflowOps[0].ParentVersion, 10); got != man.ParentVersionOverflow {
		t.Fatalf("parent_version decoded as %s, manifest says %s", got, man.ParentVersionOverflow)
	}

	if len(man.AuthoredAtRejects) != len(timeRejectCases) {
		t.Fatalf("the manifest lists %d reject cases, this build has %d", len(man.AuthoredAtRejects), len(timeRejectCases))
	}
	for _, wire := range man.AuthoredAtRejects {
		if _, err := DecodeBlob(timeProbeBlob(wire)); err == nil {
			t.Fatalf("authored_at %q must be refused: the manifest promises the TypeScript executor refuses it", wire)
		}
	}
}

// TestTypeScriptSealedBlobsOpenInGo closes the direction a Go-authored fixture
// set cannot: a TypeScript port that reads Go's bytes perfectly and WRITES
// subtly wrong ones passes every other test in this file, and would then be
// discovered by the server rejecting a device's uploads — or worse, by the
// server accepting them and no other device being able to open them.
//
// The fixtures are produced by `cd client && bun run gen-fixtures` and
// committed; that script also asserts the bytes it is about to write are the
// bytes the current TypeScript produces, so a stale set fails on the TS side.
func TestTypeScriptSealedBlobsOpenInGo(t *testing.T) {
	dir := filepath.Join(conformanceDir(), "ts")
	checkFixtures(t, dir)

	// And the ops inside must be the ops the TypeScript claimed to write. The
	// comparison is on values, never on bytes: Go escapes <, > and & as <
	// and friends where JSON.stringify does not, so the two encoders produce
	// different bytes for the same op — which is exactly why the ampersand
	// fixture is in the set.
	var sealer blob.PlaintextSealer
	man := readBlobManifest(t, dir)
	found := 0
	for _, f := range man.Fixtures {
		if f.Kind != KindOps {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(dir, f.File))
		if err != nil {
			t.Fatal(err)
		}
		plaintext, err := sealer.Open(f.Envelope.blobEnvelope(t), blob.Sealed{Bytes: raw, SizeBucket: len(raw)})
		if err != nil {
			t.Fatalf("%s: %v", f.File, err)
		}
		ops, err := DecodeBlob(plaintext)
		if err != nil {
			t.Fatalf("%s: %v", f.File, err)
		}
		if len(ops) == 0 {
			t.Fatalf("%s: TypeScript wrote an empty op blob", f.File)
		}
		found++

		if f.File == "ts-hot-dev-a-7.bin" {
			want := goldenOps()
			if len(ops) != len(want) {
				t.Fatalf("%s: %d ops, want %d", f.File, len(ops), len(want))
			}
			for i := range want {
				if ops[i].Type != want[i].Type || ops[i].OpID != want[i].OpID {
					t.Fatalf("%s: op %d is %s/%s, want %s/%s", f.File, i, ops[i].Type, ops[i].OpID, want[i].Type, want[i].OpID)
				}
				if !ops[i].AuthoredAt.Equal(want[i].AuthoredAt) {
					t.Fatalf("%s: op %d authored at %v, want %v — the two executors must read the same INSTANT",
						f.File, i, ops[i].AuthoredAt, want[i].AuthoredAt)
				}
				if (ops[i].ParentVersion == nil) != (want[i].ParentVersion == nil) {
					t.Fatalf("%s: op %d parent_version presence differs", f.File, i)
				}
				if ops[i].ParentVersion != nil && *ops[i].ParentVersion != *want[i].ParentVersion {
					t.Fatalf("%s: op %d parent_version is %d, want %d", f.File, i, *ops[i].ParentVersion, *want[i].ParentVersion)
				}
				if (ops[i].Entity == nil) != (want[i].Entity == nil) {
					t.Fatalf("%s: op %d entity presence differs", f.File, i)
				}
				if ops[i].Entity != nil && (ops[i].Entity.Kind != want[i].Entity.Kind || ops[i].Entity.ID != want[i].Entity.ID) {
					t.Fatalf("%s: op %d entity is %+v, want %+v", f.File, i, ops[i].Entity, want[i].Entity)
				}
				if ops[i].IngestID != want[i].IngestID {
					t.Fatalf("%s: op %d ingest_id is %q, want %q", f.File, i, ops[i].IngestID, want[i].IngestID)
				}
				var gotPayload, wantPayload any
				if err := json.Unmarshal(ops[i].Payload, &gotPayload); err != nil {
					t.Fatal(err)
				}
				if err := json.Unmarshal(want[i].Payload, &wantPayload); err != nil {
					t.Fatal(err)
				}
				if !jsonEqual(gotPayload, wantPayload) {
					t.Fatalf("%s: op %d payload is %s, want %s", f.File, i, ops[i].Payload, want[i].Payload)
				}
			}
		}

		if f.File == "ts-hot-dev-a-9-escapes.bin" {
			// The escaping fixture: Go must read back the exact strings the
			// TypeScript wrote, including the characters Go's own encoder would
			// have escaped.
			var payload struct {
				Merchant string `json:"merchant_raw"`
				Note     string `json:"note"`
			}
			if err := json.Unmarshal(ops[0].Payload, &payload); err != nil {
				t.Fatal(err)
			}
			// U+2028 is in the set on purpose: Go's encoder escapes it and
			// JSON.stringify does not, so it is the sharpest form of the
			// escaping asymmetry this fixture exists to prove is harmless.
			for _, want := range []string{"&", "<", ">", "\u2028"} {
				if !strings.Contains(payload.Note, want) {
					t.Fatalf("%s: note %q lost %q in transit", f.File, payload.Note, want)
				}
			}
			if payload.Merchant != "كارفور" {
				t.Fatalf("%s: merchant is %q, want the Arabic original", f.File, payload.Merchant)
			}
		}
	}
	if found < 2 {
		t.Fatalf("expected at least two TypeScript-authored op blobs, found %d", found)
	}
}

// jsonEqual compares two decoded JSON values structurally.
func jsonEqual(a, b any) bool {
	x, errA := json.Marshal(a)
	y, errB := json.Marshal(b)
	return errA == nil && errB == nil && bytes.Equal(x, y)
}
