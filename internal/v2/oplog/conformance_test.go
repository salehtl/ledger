// writeFixturesEnv gates the writer. A test that rewrites its own reference on
// every run pins nothing — it would silently re-bless whatever the code now
// produces, which is the one thing a golden file exists to prevent — so writing
// is opt-in and the fixtures are committed.
const writeFixturesEnv = "LEDGER_WRITE_CONFORMANCE"

// conformanceUser is the user id every fixture is sealed for. It is the same
// value package blob's own tests use, so a fixture's AAD is readable at a glance.
var conformanceUser = uuid.MustParse("11111111-1111-1111-1111-111111111111")

// ---------------------------------------------------------------------------
// The manifest shapes. Every integer that is an int64 on the wire is a decimal
// STRING here for the same reason it is one in the op model: a JSON number
// parsed by JavaScript is a float64.
// ---------------------------------------------------------------------------

type fixtureEnvelope struct {
	UserID        string `json:"user_id"`
	Stream        string `json:"stream"`
	WriterID      string `json:"writer_id"`
	WriterCounter string `json:"writer_counter"`
}

func (e fixtureEnvelope) blobEnvelope(t *testing.T) blob.Envelope {
	t.Helper()
	id, err := uuid.Parse(e.UserID)
	if err != nil {
		t.Fatalf("fixture envelope has an unparseable user id %q: %v", e.UserID, err)
	}
	counter, err := strconv.ParseInt(e.WriterCounter, 10, 64)
	if err != nil {
		t.Fatalf("fixture envelope has an unparseable counter %q: %v", e.WriterCounter, err)
	}
	return blob.Envelope{UserID: id, Stream: e.Stream, WriterID: e.WriterID, WriterCounter: counter}
}

type blobFixture struct {
	File                  string          `json:"file"`
	Note                  string          `json:"note"`
	Kind                  string          `json:"kind"` // KindOps or KindRawBody
	Envelope              fixtureEnvelope `json:"envelope"`
	ExpectAAD             string          `json:"expect_aad"`
	ExpectBucket          int             `json:"expect_bucket"`
	ExpectPlaintextBase64 string          `json:"expect_plaintext_base64"`
	// ExpectPrePadLength is the framed length before bucket padding. It is what
	// makes the boundary fixture a boundary fixture, and it is unreadable from
	// the padded bytes without walking the framing — which is the point.
	ExpectPrePadLength int `json:"expect_pre_pad_length"`
}

type chainStep struct {
	FillByte   string `json:"fill_byte"` // one hex byte, repeated
	Length     int    `json:"length"`
	ExpectHash string `json:"expect_hash"` // hex; SHA256(prev || bytes)
}

type blobManifest struct {
	Note        string        `json:"note"`
	Buckets     []int         `json:"buckets"`
	NonceSize   int           `json:"nonce_size"`
	TagSize     int           `json:"tag_size"`
	ZeroHashHex string        `json:"zero_hash_hex"`
	ChainSteps  []chainStep   `json:"chain_steps"`
	Fixtures    []blobFixture `json:"fixtures"`
}

type opExpect struct {
	Type             string `json:"type"`
	OpID             string `json:"op_id"`
	AuthoredAtUnixMs string `json:"authored_at_unix_ms"`
	HasEntity        bool   `json:"has_entity"`
	// ParentVersion is a decimal string or null, mirroring the ambiguity the
	// wire deliberately does not have: on the wire parent_version is a raw JSON
	// NUMBER (see the note in the manifest), but a manifest that repeated that
	// choice could not express a value above 2^53 for the TypeScript reader to
	// check itself against.
	ParentVersion *string `json:"parent_version"`
	IngestID      string  `json:"ingest_id"`
}

type timeCase struct {
	Wire         string `json:"wire"`
	ExpectUnixMs string `json:"expect_unix_ms"`
}

type opManifest struct {
	Note                   string     `json:"note"`
	SchemaVersion          int        `json:"schema_version"`
	Types                  []string   `json:"types"`
	ParentFree             []string   `json:"parent_free"`
	GoldenOpsBase64        string     `json:"golden_ops_base64"`
	GoldenRawBodyBase64    string     `json:"golden_raw_body_base64"`
	GoldenCheckpointBase64 string     `json:"golden_checkpoint_base64"`
	ExpectOps              []opExpect `json:"expect_ops"`
	AuthoredAtCases        []timeCase `json:"authored_at_cases"`
	// ParentVersionOverflowBase64 is an op blob this executor accepts and the
	// TypeScript one must REFUSE: parent_version is a raw JSON number on the
	// frozen wire, so an int64 above 2^53 is expressible here and is already
	// rounded by JSON.parse before any TypeScript code sees it. The asymmetry is
	// a property of the format, not a bug in either port, so it is pinned as a
	// shared artifact rather than asserted from an inline literal on one side.
	ParentVersionOverflowBase64 string `json:"parent_version_overflow_base64"`
	// ParentVersionOverflow is that same value as a decimal string, which is the
	// only way this manifest can state it without being lossy itself.
	ParentVersionOverflow string `json:"parent_version_overflow"`
	// AuthoredAtRejects are timestamps BOTH executors must refuse. It is a
	// shared artifact rather than two independent literals on purpose: the whole
	// class of bug here is one side quietly accepting what the other refuses, and
	// two hand-maintained lists drift into exactly that.
	AuthoredAtRejects []string `json:"authored_at_rejects"`
}

// timeAcceptCases are timestamps both executors must read as the same instant.
var timeAcceptCases = []string{
	"2026-06-05T10:00:00Z",
	"2026-06-05T10:00:00.1Z",
	"2026-06-05T10:00:00.0015Z",    // truncates to 1ms, never rounds to 2
	"2026-06-05T10:00:00.0000015Z", // finer than a JS Date can hold
	"2026-06-05T14:00:00.5+04:00",
	"2026-06-05T10:00:00-00:00",
	"2026-06-05T10:00:00+23:59", // the largest offset both accept
	"2024-02-29T00:00:00Z",      // a real leap day
	"2000-02-29T00:00:00Z",      // divisible by 400
}

// timeRejectCases are timestamps both executors must refuse. Each was MEASURED
// against both runtimes; the comments name which side was the lenient one
// before this was pinned.
var timeRejectCases = []string{
	"2026-06-05T24:00:00Z",      // Date.parse rolled it to the next day
	"2026-02-30T10:00:00Z",      // Date.parse rolled it to MARCH 2nd
	"2026-02-29T00:00:00Z",      // 2026 is not a leap year
	"2026-13-05T10:00:00Z",      // month 13
	"2026-06-05T10:60:00Z",      // minute 60
	"2026-06-05T10:00:60Z",      // second 60: no leap seconds
	"2026-06-05T10:00:00+24:00", // stock Go accepted it; Date.parse refuses
	"2026-06-05T10:00:00+24:60", // stock Go read it as -25h
	"2026-06-05T10:00:00+00:60", // stock Go read it as -1h
	"2026-06-05t10:00:00z",      // Date.parse accepts lowercase; RFC3339 layout does not
	"2026-06-05 10:00:00Z",      // space separator
	"2026-06-05T10:00:00",       // no zone
	"2026-06-05T10:00:00.Z",     // empty fraction
	"0001-01-01T00:00:00Z",      // Go's zero time
	"2026-06-05",
	"June 5 2026",
	"",
}

